"""Internationalisation de l'interface (en / fr / es).

Table de chaînes unique : ``TR[langue][cle]``. La langue courante est un
état global d'application (une seule fenêtre) : :func:`set_language` avant
de construire/redessiner l'interface, :func:`t` pour lire une chaîne.

Les placeholders utilisent ``str.format`` : ``t("st_saved", p="/x")``.
Le marqueur ``{s}``` porte le pluriel (``""`` ou ``"S"``).
"""

from __future__ import annotations

import locale
from typing import Dict, Tuple

LANGUAGES: Tuple = ("en", "fr", "es")

_current: str = "en"


def detect_language() -> str:
    """Devine la langue à partir de la locale système (sinon « en »)."""
    try:
        loc = (locale.getdefaultlocale()[0] or "").lower()
    except Exception:  # noqa: BLE001 — locale absente
        loc = ""
    for code in LANGUAGES:
        if loc.startswith(code):
            return code
    return "en"


def set_language(lang: str) -> None:
    global _current
    if lang in LANGUAGES:
        _current = lang


def get_language() -> str:
    return _current


def t(key: str, **fmt) -> str:
    """Chaîne de la langue courante (repli : anglais, puis la clé)."""
    table = TR.get(_current, TR["en"])
    s = table.get(key) or TR["en"].get(key) or key
    if fmt:
        try:
            s = s.format(**fmt)
        except (KeyError, IndexError):
            pass
    return s


